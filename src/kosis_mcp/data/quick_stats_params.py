def get_quick_stats_param(keyword: str) -> QuickStatsParam | None:
    if not keyword:
        return None
    trimmed = keyword.strip()
    if not trimmed:
        return None
    if trimmed in QUICK_STATS_PARAMS:
        return QUICK_STATS_PARAMS[trimmed]
    lower = trimmed.lower()
    alias_target = KEYWORD_ALIASES.get(trimmed) or KEYWORD_ALIASES.get(lower)
    if alias_target and alias_target in QUICK_STATS_PARAMS:
        return QUICK_STATS_PARAMS[alias_target]
    target = KEYWORD_LOOKUP.get(normalize_keyword_key(trimmed))
    if target and target in QUICK_STATS_PARAMS:
        return QUICK_STATS_PARAMS[target]
    return None

def get_region_code(param: QuickStatsParam, region_name: str) -> str | None:
    from kosis_mcp.utils.regions import normalize_province_name
    codes = param.get("regionCodes")
    if not codes:
        return None
    trimmed = region_name.strip()
    if trimmed in codes:
        return codes[trimmed]
    short = normalize_province_name(trimmed)
    return codes.get(short)
